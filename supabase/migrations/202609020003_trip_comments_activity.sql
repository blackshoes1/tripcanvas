-- 함께하기 3단계 — 코멘트 · 활동 기록 · 실시간 전달.
--
-- 코멘트(§14)는 후보 장소에 붙는 짧은 의견이다. 채팅이 아니다(§15) — 장소 중심 토론만. @mention 없음(§52).
-- 활동 기록(§37~§39)은 "누가 무엇을 했는가"의 **의미 있는** 변경만 남긴다. 트리거가 쓴다 —
-- 1·2단계 RPC 본문을 건드리지 않고, 어떤 경로로 바뀌든 같은 기록이 남는다.
-- 실시간(§40·§41)은 **전달 수단**일 뿐이다. source of truth는 DB고, 클라이언트는 이벤트를 받으면
-- 그 내용을 믿지 않고 RPC로 다시 읽는다. 실시간이 죽어도 앱은 그대로 돈다(탭 복귀 시 pull이 폴백).
--
-- 접근 경계는 여기(RLS)다. 두 테이블 모두 읽기는 활성 멤버만, 쓰기 정책은 없고 RPC·트리거만 쓴다.

-- ── 테이블 ──────────────────────────────────────────────────────────────────

do $$ declare t text; begin
  select format_type(a.atttypid, a.atttypmod) into t
    from pg_attribute a where a.attrelid='public.trips'::regclass and a.attname='id';
  execute format($sql$
    create table if not exists public.trip_comments (
      id bigint generated by default as identity primary key,
      trip_id %1$s not null references public.trips(id) on delete cascade,
      -- 코멘트는 후보에만 붙는다. 문서 안 장소에는 안정적인 id가 없어 붙일 곳이 없다(scheduled_ref와 같은 이유).
      candidate_id bigint not null references public.trip_candidates(id) on delete cascade,
      user_id uuid not null references auth.users(id) on delete cascade,
      body text not null check (btrim(body) <> '' and length(body) <= 500),
      created_at timestamptz not null default now(),
      updated_at timestamptz not null default now()
    )$sql$, t);
  execute format($sql$
    create table if not exists public.trip_activity (
      id bigint generated by default as identity primary key,
      trip_id %1$s not null references public.trips(id) on delete cascade,
      -- 누가. 계정이 지워지면 null — 기록은 남고 이름표만 '멤버'가 된다.
      actor_id uuid references auth.users(id) on delete set null,
      kind text not null check (kind in (
        'MEMBER_JOINED','MEMBER_LEFT','MEMBER_REMOVED',
        'CANDIDATE_PROPOSED','CANDIDATE_SCHEDULED','REACTION','COMMENT_ADDED',
        'SCHEDULE_CHANGED','BOOKING_ADDED')),
      -- 문장을 만들 재료(후보 이름·반응·일차 등). 화면 문장은 클라이언트(collab.js activityText)가 만든다(§39).
      subject jsonb not null default '{}'::jsonb,
      created_at timestamptz not null default now()
    )$sql$, t);
end $$;

create index if not exists trip_comments_cand_idx on public.trip_comments(candidate_id, created_at);
create index if not exists trip_activity_trip_idx on public.trip_activity(trip_id, id desc);

