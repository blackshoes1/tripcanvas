-- ── 코멘트 RPC ──────────────────────────────────────────────────────────────

-- 코멘트는 의견이다 — 보기 권한도 남긴다(반응과 같은 규칙). 멤버가 아니면 42501.
create or replace function public.add_candidate_comment(p_candidate_id bigint, p_body text)
returns bigint language plpgsql security definer set search_path=public as $$
declare v_uid uuid := auth.uid(); v_cand public.trip_candidates%rowtype; v_body text; v_id bigint;
begin
  if v_uid is null then raise exception 'authentication required'; end if;
  v_body := nullif(left(btrim(coalesce(p_body,'')), 500), '');
  if v_body is null then raise exception 'BODY_REQUIRED' using errcode='22023', hint='빈 코멘트는 남길 수 없다'; end if;
  select c.* into v_cand from public.trip_candidates c where c.id=p_candidate_id;
  if not found or public.tc_trip_role(v_cand.trip_id) is null then
    raise exception 'TRIP_FORBIDDEN' using errcode='42501', hint='이 여행의 멤버가 아니다';
  end if;
  insert into public.trip_comments(trip_id, candidate_id, user_id, body)
  values (v_cand.trip_id, v_cand.id, v_uid, v_body) returning id into v_id;
  return v_id;
end $$;

-- 지우기는 쓴 사람이나 주최자만. 이미 없으면 false(두 번 눌러도 같다).
create or replace function public.delete_candidate_comment(p_comment_id bigint)
returns boolean language plpgsql security definer set search_path=public as $$
declare v_uid uuid := auth.uid(); v_cm public.trip_comments%rowtype; v_owner uuid;
begin
  if v_uid is null then raise exception 'authentication required'; end if;
  select cm.* into v_cm from public.trip_comments cm where cm.id=p_comment_id for update;
  if not found then return false; end if;
  if public.tc_trip_role(v_cm.trip_id) is null then
    raise exception 'TRIP_FORBIDDEN' using errcode='42501', hint='이 여행의 멤버가 아니다';
  end if;
  select t.user_id into v_owner from public.trips t where t.id=v_cm.trip_id;
  if v_uid<>v_cm.user_id and v_uid<>v_owner then
    raise exception 'TRIP_FORBIDDEN' using errcode='42501', hint='코멘트는 쓴 사람이나 주최자만 지운다';
  end if;
  delete from public.trip_comments cm where cm.id=v_cm.id;
  return true;
end $$;

create or replace function public.list_candidate_comments(p_candidate_id bigint)
returns table(id bigint, body text, author_label text, mine boolean, created_at timestamptz)
language sql stable security invoker set search_path=public as $$
  select cm.id, cm.body, public.tc_member_label(cm.trip_id, cm.user_id), cm.user_id=auth.uid(), cm.created_at
    from public.trip_comments cm
   where cm.candidate_id=p_candidate_id
   order by cm.created_at, cm.id
$$;

-- list_trip_candidates에 comment_count를 더한다. 반환형이 바뀌므로 create or replace로는 안 되고 지웠다 만든다.
drop function if exists public.list_trip_candidates(text);
create function public.list_trip_candidates(p_client_id text)
returns table(id bigint, title text, place_id text, lat double precision, lng double precision,
              addr text, note text, url text, status text, scheduled_ref text,
              proposed_by_label text, mine boolean, my_reaction text,
              must_count int, ok_count int, pass_count int, reactions jsonb, comment_count int, created_at timestamptz)
language sql stable security invoker set search_path=public as $$
  with trip as (
    select t.id from public.trips t
     where t.client_id=p_client_id and t.deleted_at is null and public.tc_trip_role(t.id) is not null
     order by (t.user_id=auth.uid()) desc, t.id limit 1
  )
  select c.id, c.title, c.place_id, c.lat, c.lng, c.addr, c.note, c.url, c.status, c.scheduled_ref,
         public.tc_member_label(c.trip_id, c.proposed_by), c.proposed_by=auth.uid(),
         (select r.reaction from public.candidate_reactions r where r.candidate_id=c.id and r.user_id=auth.uid()),
         (select count(*)::int from public.candidate_reactions r where r.candidate_id=c.id and r.reaction='MUST'),
         (select count(*)::int from public.candidate_reactions r where r.candidate_id=c.id and r.reaction='OK'),
         (select count(*)::int from public.candidate_reactions r where r.candidate_id=c.id and r.reaction='PASS'),
         coalesce((select jsonb_agg(jsonb_build_object(
                     'name', public.tc_member_label(c.trip_id, r.user_id),
                     'reaction', r.reaction,
                     'me', r.user_id=auth.uid()) order by r.created_at, r.id)
                     from public.candidate_reactions r where r.candidate_id=c.id), '[]'::jsonb),
         (select count(*)::int from public.trip_comments cm where cm.candidate_id=c.id),
         c.created_at
    from public.trip_candidates c
   where c.trip_id=(select id from trip)
   order by c.created_at desc, c.id desc
$$;

-- ── 활동 기록 RPC ───────────────────────────────────────────────────────────

-- 최근 활동. 이름표는 읽는 시점에 만든다 — 나간 사람도 trip_members 행은 남아 있어 이름이 나온다.
-- 클라이언트가 문장을 만들 재료만 준다(§39 — 내부 구조를 그대로 노출하지 않는다는 뜻은 '문장'을 여기서 굳히지 않는 것이다).
create or replace function public.list_trip_activity(p_client_id text, p_limit int default 40)
returns table(id bigint, kind text, actor_label text, mine boolean, member_label text, subject jsonb, created_at timestamptz)
language sql stable security invoker set search_path=public as $$
  with trip as (
    select t.id from public.trips t
     where t.client_id=p_client_id and t.deleted_at is null and public.tc_trip_role(t.id) is not null
     order by (t.user_id=auth.uid()) desc, t.id limit 1
  )
  select a.id, a.kind,
         coalesce(public.tc_member_label(a.trip_id, a.actor_id), '멤버'),
         a.actor_id=auth.uid(),
         case when a.subject ? 'member_id'
              then coalesce(public.tc_member_label(a.trip_id, (a.subject->>'member_id')::uuid), '멤버') end,
         a.subject, a.created_at
    from public.trip_activity a
   where a.trip_id=(select id from trip)
   order by a.id desc
   limit greatest(1, least(coalesce(p_limit,40), 200))
$$;

