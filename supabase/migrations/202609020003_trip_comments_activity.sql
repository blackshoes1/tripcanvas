-- ── 1단계 트리거 함수의 search_path 고정 (Supabase 린터 WARN) ────────────────
-- 직접 호출은 PostgreSQL이 막지만(trigger 반환형), 본문을 그대로 두고 search_path만 못 박는다.

create or replace function public.tc_trips_lock_owner() returns trigger
language plpgsql set search_path=public as $$
begin
  if new.user_id is distinct from old.user_id then
    raise exception 'TRIP_OWNER_LOCKED' using errcode='42501', hint='소유권 이전은 아직 지원하지 않는다';
  end if;
  return new;
end $$;

create or replace function public.tc_touch_updated_at() returns trigger
language plpgsql set search_path=public as $$
begin new.updated_at=now(); return new; end $$;

-- ── 활동 기록 — 트리거가 쓴다 ───────────────────────────────────────────────

-- 한 줄 넣기. 트리거 안에서만 불린다 — 클라이언트는 실행 권한이 없다.
create or replace function public.tc_log_activity(p_trip_id public.trips.id%type, p_kind text, p_subject jsonb default '{}'::jsonb)
returns void language plpgsql security definer set search_path=public as $$
begin
  insert into public.trip_activity(trip_id, actor_id, kind, subject)
  values (p_trip_id, auth.uid(), p_kind, coalesce(p_subject,'{}'::jsonb));
end $$;

-- 후보: 담기 · 일정에 넣기. 빼기는 기록하지 않는다(§38 — 의미 있는 변경만).
create or replace function public.tc_act_candidates() returns trigger
language plpgsql security definer set search_path=public as $$
begin
  if tg_op='INSERT' then
    perform public.tc_log_activity(new.trip_id,'CANDIDATE_PROPOSED',jsonb_build_object('title',new.title,'candidate_id',new.id));
  elsif tg_op='UPDATE' and new.status='SCHEDULED' and old.status is distinct from 'SCHEDULED' then
    perform public.tc_log_activity(new.trip_id,'CANDIDATE_SCHEDULED',jsonb_build_object('title',new.title,'candidate_id',new.id,'ref',new.scheduled_ref));
  end if;
  return null;
end $$;
drop trigger if exists tc_act_candidates on public.trip_candidates;
create trigger tc_act_candidates after insert or update on public.trip_candidates
  for each row execute function public.tc_act_candidates();

-- 반응: 남기기·바꾸기만. 거두기(delete)는 기록하지 않는다.
-- 제안자에게 자동으로 붙는 MUST(add_trip_candidate)는 같은 트랜잭션이라 created_at이 같다 — 그건 뺀다.
create or replace function public.tc_act_reactions() returns trigger
language plpgsql security definer set search_path=public as $$
declare v_cand public.trip_candidates%rowtype;
begin
  select c.* into v_cand from public.trip_candidates c where c.id=new.candidate_id;
  if not found then return null; end if;
  if v_cand.proposed_by=new.user_id and v_cand.created_at>=now()-interval '1 second' then return null; end if;
  if tg_op='UPDATE' and old.reaction=new.reaction then return null; end if;
  perform public.tc_log_activity(v_cand.trip_id,'REACTION',
    jsonb_build_object('title',v_cand.title,'candidate_id',v_cand.id,'reaction',new.reaction));
  return null;
end $$;
drop trigger if exists tc_act_reactions on public.candidate_reactions;
create trigger tc_act_reactions after insert or update on public.candidate_reactions
  for each row execute function public.tc_act_reactions();

create or replace function public.tc_act_comments() returns trigger
language plpgsql security definer set search_path=public as $$
declare v_title text;
begin
  select c.title into v_title from public.trip_candidates c where c.id=new.candidate_id;
  perform public.tc_log_activity(new.trip_id,'COMMENT_ADDED',
    jsonb_build_object('title',coalesce(v_title,''),'candidate_id',new.candidate_id,'excerpt',left(new.body,60)));
  return null;
end $$;
drop trigger if exists tc_act_comments on public.trip_comments;
create trigger tc_act_comments after insert on public.trip_comments
  for each row execute function public.tc_act_comments();

-- 멤버: 참여 · 나감 · 내보내짐. 소유자 행(여행 생성 트리거·백필)은 기록하지 않는다 — 혼자 만든 여행에 "참여했어요"가 뜨면 이상하다.
-- MEMBER_REMOVED의 actor는 내보낸 소유자고, 누가 내보내졌는지는 subject.member_id로 남긴다.
create or replace function public.tc_act_members() returns trigger
language plpgsql security definer set search_path=public as $$
declare v_kind text;
begin
  if new.role='OWNER' then return null; end if;
  if tg_op='INSERT' then
    if new.status='ACTIVE' then v_kind:='MEMBER_JOINED'; end if;
  elsif new.status is distinct from old.status then
    if new.status='ACTIVE' then v_kind:='MEMBER_JOINED';
    elsif new.status='LEFT' then v_kind:='MEMBER_LEFT';
    elsif new.status='REMOVED' then v_kind:='MEMBER_REMOVED';
    end if;
  end if;
  if v_kind is null then return null; end if;
  perform public.tc_log_activity(new.trip_id, v_kind, jsonb_build_object('member_id',new.user_id,'role',new.role));
  return null;
end $$;
drop trigger if exists tc_act_members on public.trip_members;
create trigger tc_act_members after insert or update on public.trip_members
  for each row execute function public.tc_act_members();

-- 여행 문서: 일정 변경 · 예약 추가. **다른 활성 멤버가 있을 때만** 남긴다 — 혼자 쓰는 여행의 저장마다
-- 행을 쌓고 실시간으로 내보낼 이유가 없다(§95). 문서 저장은 잦으므로 여행당 최근 300건만 남긴다.
-- 같은 사람의 연속 저장을 여기서 합치지 않는 이유: 행을 UPDATE하면 실시간 INSERT 구독자가 못 받는다.
-- 읽기 쉬운 묶음은 화면(collab.js condenseActivity)이 만든다(§39).
create or replace function public.tc_act_trips() returns trigger
language plpgsql security definer set search_path=public as $$
declare v_old int; v_new int; v_kind text; v_subject jsonb;
begin
  if new.deleted_at is not null then return null; end if;
  if not exists (select 1 from public.trip_members m
                  where m.trip_id=new.id and m.user_id<>new.user_id and m.status='ACTIVE') then
    return null;
  end if;
  v_old := case when jsonb_typeof(old.data->'bookings')='array' then jsonb_array_length(old.data->'bookings') else 0 end;
  v_new := case when jsonb_typeof(new.data->'bookings')='array' then jsonb_array_length(new.data->'bookings') else 0 end;
  if v_new > v_old then
    v_kind := 'BOOKING_ADDED'; v_subject := jsonb_build_object('count', v_new - v_old);
  else
    v_kind := 'SCHEDULE_CHANGED'; v_subject := jsonb_build_object('revision', new.revision);
  end if;
  perform public.tc_log_activity(new.id, v_kind, v_subject);
  delete from public.trip_activity a
   where a.trip_id=new.id
     and a.id < coalesce((select x.id from public.trip_activity x where x.trip_id=new.id order by x.id desc offset 300 limit 1), 0);
  return null;
end $$;
drop trigger if exists tc_act_trips on public.trips;
create trigger tc_act_trips after update of data on public.trips
  for each row when (old.data is distinct from new.data) execute function public.tc_act_trips();

